#!/usr/bin/env node
// scripts/phase3-build-load-sql.mjs
// Turn ./phase3-export/*.json into one dependency-ordered, idempotent SQL file.
//
// No new dependency: this emits SQL, and psql loads it. psql talks to any server version, which
// is what made the whole DDL step possible after pg_dump refused.
//
// THREE THINGS IT GETS RIGHT THAT A NAIVE DUMP WOULD NOT:
//
// 1. LOAD ORDER. Parents before children, topologically sorted from the foreign keys declared in
//    004_neon_ready.sql. Without it the first FK insert fails and the order has to be guessed.
// 2. COLUMN TYPES. Supabase's client returns both jsonb and text[] as plain JS arrays, so the
//    value alone cannot tell you which cast to emit. Types are read from the DDL instead, so
//    `genre text[]` and `scheduled_dates jsonb` are each written correctly.
// 3. IDEMPOTENCY. Every insert is ON CONFLICT (id) DO NOTHING, so a partial load can be re-run
//    rather than unpicked. Tables without an id column fall back to ON CONFLICT DO NOTHING.
//
// Usage:
//   node scripts/phase3-build-load-sql.mjs            # -> phase3-export/load.sql
//   psql "$NEON_URL" -v ON_ERROR_STOP=1 -f phase3-export/load.sql

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const DDL = readFileSync('supabase/neon/004_neon_ready.sql', 'utf8');
const EXPORT = 'phase3-export';
const manifest = JSON.parse(readFileSync(`${EXPORT}/_manifest.json`, 'utf8'));

// --- column types, per table, from the CREATE TABLE blocks ---
const colTypes = {};
{
  const lines = DDL.split('\n');
  let cur = null;
  for (const l of lines) {
    const m = l.match(/^CREATE TABLE IF NOT EXISTS ([a-z_]+) \($/);
    if (m) { cur = m[1]; colTypes[cur] = {}; continue; }
    if (cur && l === ');') { cur = null; continue; }
    if (cur) {
      const c = l.match(/^\s+([a-z_]+) ([a-z0-9_ ()[\],."]+?)(?: DEFAULT | NOT NULL|,?$)/i);
      if (c) colTypes[cur][c[1]] = c[2].trim().replace(/,$/, '');
    }
  }
}

// --- FK graph -> load order ---
const deps = {};
for (const t of Object.keys(manifest)) deps[t] = new Set();
for (const l of DDL.split('\n')) {
  const m = l.match(/^ALTER TABLE ([a-z_]+) ADD CONSTRAINT [a-z_]+ FOREIGN KEY \([a-z_, ]+\) REFERENCES ([a-z_]+)\(/);
  if (!m) continue;
  const [, child, parent] = m;
  // Self-references (e.g. a parent_id) do not constrain table order.
  if (child !== parent && deps[child] && manifest[parent] !== undefined) deps[child].add(parent);
}
const order = [];
const seen = new Set();
const visit = (t, stack = new Set()) => {
  if (seen.has(t) || stack.has(t)) return; // a cycle cannot be ordered; emit and let psql judge
  stack.add(t);
  for (const p of deps[t] ?? []) visit(p, stack);
  stack.delete(t);
  seen.add(t); order.push(t);
};
for (const t of Object.keys(manifest)) visit(t);

// --- literal rendering ---
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
function lit(v, type) {
  if (v === null || v === undefined) return 'NULL';
  const t = (type ?? '').toLowerCase();
  if (t.endsWith('[]')) {
    // text[] and friends: a Postgres array literal, not JSON.
    const inner = (Array.isArray(v) ? v : [v]).map((x) => (x === null ? 'NULL' : `"${String(x).replace(/(["\\])/g, '\\$1')}"`));
    return `${q(`{${inner.join(',')}}`)}::${t}`;
  }
  if (t.includes('json')) return `${q(JSON.stringify(v))}::jsonb`;
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`; // untyped object: best effort
  return q(v);
}

const out = [
  '-- phase3-export/load.sql',
  '-- GENERATED by scripts/phase3-build-load-sql.mjs. Regenerate rather than editing.',
  '-- Run AFTER supabase/neon/004_neon_ready.sql has created the schema.',
  '--   psql "$NEON_URL" -v ON_ERROR_STOP=1 -f phase3-export/load.sql',
  '--',
  '-- Idempotent: every statement is ON CONFLICT DO NOTHING, so a partial load re-runs cleanly.',
  '-- Tables are ordered parents-first from the foreign keys in 004_neon_ready.sql.',
  '',
  'BEGIN;',
  '',
];

let stmts = 0;
for (const table of order) {
  const path = `${EXPORT}/${table}.json`;
  if (!existsSync(path)) continue;
  const rows = JSON.parse(readFileSync(path, 'utf8'));
  out.push(`-- ${table}: ${rows.length} row(s)`);
  if (rows.length === 0) { out.push(''); continue; }
  const cols = Object.keys(rows[0]);
  const types = colTypes[table] ?? {};
  const conflict = cols.includes('id') ? '(id) DO NOTHING' : 'DO NOTHING';
  for (const r of rows) {
    const vals = cols.map((c) => lit(r[c], types[c]));
    out.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${vals.join(', ')}) ON CONFLICT ${conflict};`);
    stmts++;
  }
  out.push('');
}

out.push('COMMIT;', '');
out.push('-- Verify: these counts must match phase3-export/_manifest.json');
for (const t of order) if (manifest[t] !== undefined) {
  out.push(`SELECT '${t}' AS table_name, count(*) AS rows, ${manifest[t]} AS expected FROM ${t};`);
}
writeFileSync(`${EXPORT}/load.sql`, out.join('\n'));

console.log(`load order (parents first): ${order.filter((t) => manifest[t] !== undefined).length} tables`);
console.log(`insert statements: ${stmts}`);
console.log(`\nwrote ${EXPORT}/load.sql`);
